package services

import "testing"

// TestIsGeneratedFile covers the cross-language generated-file detection: every
// ecosystem dupehound supports stamps its output differently, so both the
// filename-suffix and content-marker paths are exercised here, alongside
// hand-written files that must NOT be flagged.
func TestIsGeneratedFile(t *testing.T) {
	cases := []struct {
		name    string
		path    string
		content string
		want    bool
	}{
		// --- filename-suffix detection, spanning languages ---
		{"go protobuf", "api/types.pb.go", "package api\n", true},
		{"go stringer", "color_string.go", "package x\n", true},
		{"python protobuf", "svc/types_pb2.py", "x = 1\n", true},
		{"cpp protobuf header", "msg.pb.h", "#pragma once\n", true},
		{"ts graphql-codegen", "queries.generated.ts", "export const x = 1\n", true},
		{"csharp designer", "Form1.Designer.cs", "namespace App {}\n", true},
		{"dart freezed", "user.freezed.dart", "part of 'user.dart';\n", true},

		// --- content-marker detection, language-agnostic ---
		{"go marker", "x.go", "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage x\n", true},
		{"ts relay marker", "x.ts", "/**\n * @generated SignedSource<<abc>>\n */\nexport {}\n", true},
		{"csharp marker", "X.cs", "// <auto-generated>\n//   This code was generated.\n// </auto-generated>\n", true},
		{"dart marker", "x.dart", "// GENERATED CODE - DO NOT MODIFY BY HAND\n", true},
		{"java marker", "X.java", "// This file was automatically generated.\nclass X {}\n", true},
		{"python marker", "x.py", "# Generated by the protocol buffer compiler. DO NOT EDIT!\n", true},

		// --- hand-written files must not be flagged ---
		{"plain go", "main.go", "package main\nfunc main() {}\n", false},
		{"plain ts", "app.ts", "export function add(a: number, b: number) { return a + b }\n", false},
		{"comment mentioning edit", "x.go", "// Please do not edit this without review? no — written normally.\n", false},
		{"unrelated header", "x.py", "# A normal module that was written by a human, generated nothing.\n", false},

		// --- prose below the file header is documentation, not a marker ---
		// Found on real repositories: each of these silently removed a
		// hand-written file from the scan (20 files in google/guava alone).
		{
			"javadoc describing generated values", "Objects.java",
			"/*\n * Copyright (C) 2007 The Guava Authors\n */\n\npackage com.google.common.base;\n\n" +
				"/**\n * The hash code is generated by calling {@link Arrays#hashCode}.\n */\npublic final class Objects {}\n",
			false,
		},
		{
			"python docstring inside a function", "makemessages.py",
			"import os\n\ndef postprocess():\n    \"\"\"Postprocess messages generated by xgettext.\"\"\"\n    return 1\n",
			false,
		},
		{
			"sql keyword in a string", "schema.py",
			"from django.db import models\n\nSQL = \"GENERATED BY DEFAULT AS IDENTITY\"\n",
			false,
		},
		{
			"ruby comment below the requires", "request_id.rb",
			"require \"securerandom\"\n\nmodule ActionDispatch\n  # which would typically be generated by a firewall\n  class RequestId\n  end\nend\n",
			false,
		},
		{
			"test asserting on generated code text", "tests.py",
			"import unittest\n\nEXPECTED = \"# Settings file automatically generated by the test case\"\n",
			false,
		},

		// --- a real marker is still found below a license header or preamble ---
		{
			"go marker after license header", "zz_deepcopy.go",
			"/*\nCopyright The Authors.\nLicensed under the Apache License.\n*/\n\n// Code generated by deepcopy-gen. DO NOT EDIT.\n\npackage v1\n",
			true,
		},
		{"ruby schema header", "schema.rb", "# This file is auto-generated from the current state of the database.\n\nActiveRecord::Schema.define {}\n", true},
		{"python marker after shebang", "x.py", "#!/usr/bin/env python\n# -*- coding: utf-8 -*-\n# Generated by Django 4.2 on 2024-01-01\n\nfrom django.db import migrations\n", true},
		{"php marker after open tag", "x.php", "<?php\n\n/**\n * This file was automatically generated.\n */\n\nreturn [];\n", true},
		{"ts block-comment header", "graphql.schema.ts", "\n/*\n * -------------------\n * THIS FILE WAS AUTOMATICALLY GENERATED (DO NOT MODIFY)\n * -------------------\n */\n\nexport class X {}\n", true},
		{"strong marker below the header", "bundle.js", "\"use strict\";\n/** @generated by the bundler */\nmodule.exports = {};\n", true},
	}

	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			if got := isGeneratedFile(tc.path, tc.content); got != tc.want {
				t.Errorf("isGeneratedFile(%q) = %v, want %v", tc.path, got, tc.want)
			}
		})
	}
}
