package services

import (
	"regexp"
	"strings"
)

// Recognising machine-generated and minified files, which are skipped by default.

// generatedNameSuffixes are filename patterns that almost universally denote
// machine-generated source. Generated code is duplicated by construction (one
// template, many emissions), so it inflates duplication numbers and buries
// real, refactorable clones. These are skipped by default — like vendor/ and
// node_modules/ — and re-enabled with --scan-generated. The list spans the
// ecosystems dupehound supports; anything not covered here is still caught by
// the language-agnostic content marker below, which is the real workhorse.
var generatedNameSuffixes = []string{
	// protobuf / gRPC across languages
	".pb.go", ".pb.gw.go", // Go
	"_pb2.py", "_pb2_grpc.py", "_pb2.pyi", // Python
	".pb.cc", ".pb.h", // C/C++
	".pb.swift",                                                // Swift
	".pb.dart", ".pbenum.dart", ".pbgrpc.dart", ".pbjson.dart", // Dart
	// Go conventions
	"_gen.go", ".gen.go", "_string.go", ".generated.go",
	// JS / TS codegen (graphql-codegen, openapi, etc.)
	".generated.ts", ".generated.tsx", ".generated.js",
	// C# / .NET
	".designer.cs", ".g.cs", ".g.i.cs", ".generated.cs",
	// Dart / Flutter build_runner
	".g.dart", ".freezed.dart", ".gr.dart", ".config.dart",
}

// Generated-file markers come in two strengths, matched over different parts of
// the file. Both are case-insensitive and language-agnostic, covering Go's
// `Code generated … DO NOT EDIT`, the `@generated` tag used by Relay /
// GraphQL-codegen / SignedSource (JS/TS), .NET's `<auto-generated>`, Dart's
// `GENERATED CODE - DO NOT MODIFY BY HAND`, protobuf banners, etc.
//
// generatedStrongRE holds phrases that only a generator writes. They are
// trusted anywhere in the first few KB.
//
// generatedHeaderRE holds phrases that are also ordinary English — "the hash
// code is generated by calling…" — so they count only inside the file's leading
// comment block, where a generator stamps its banner. Matching them further
// down silently dropped hand-written files whose documentation used the words.
//
// Bare "do not edit" is deliberately excluded from both — it appears in
// hand-written comments often enough to cause false skips.
var (
	generatedStrongRE = regexp.MustCompile(`(?i)` + strings.Join([]string{
		`code generated .*do not edit`,
		`do not modify by hand`,
		`@generated`,
		`@autogenerated`,
		`<auto-?generated`,
	}, "|"))
	// Matched per header line, with comment markers stripped: a banner states
	// the fact up front ("Generated by protoc"), while prose mentions it in
	// passing ("…compare the object files generated by two toolchains").
	generatedHeaderRE = regexp.MustCompile(`(?i)` + strings.Join([]string{
		`^(?:code generated|generated code|generated by|automatically generated|auto-?generated)\b`,
		`this (?:file|code) (?:is|was) (?:auto(?:matically)?[- ]?)?generated`,
		`auto-?generated (?:file|code|by|from)`,
	}, "|"))
)

// Minified source is build output: one enormous line, or a handful of them.
// minifiedLineLen is far beyond anything a formatter or a person produces.
// Such lines must make up most of the file and the file must average out as
// long-lined overall, so hand-written code holding one big literal is kept.
const (
	minifiedLineLen    = 2000
	minifiedAvgLineLen = 500
)

// isMinified reports whether content is dominated by extremely long lines.
func isMinified(content string) bool {
	long, lines := 0, 0
	for line := range strings.SplitSeq(content, "\n") {
		lines++
		if len(line) >= minifiedLineLen {
			long += len(line)
		}
	}
	return long*2 > len(content) && len(content)/lines >= minifiedAvgLineLen
}

// isGeneratedFile reports whether a file is machine-generated — by filename
// suffix (cheap, language-spanning) or by the standard in-file marker, scanned
// over the first few KB only since generators always place it at the top.
func isGeneratedFile(path, content string) bool {
	lower := strings.ToLower(path)
	for _, suf := range generatedNameSuffixes {
		if strings.HasSuffix(lower, suf) {
			return true
		}
	}
	head := content
	if len(head) > 4096 {
		head = head[:4096]
	}
	if generatedStrongRE.MatchString(head) {
		return true
	}
	for line := range strings.SplitSeq(leadingCommentBlock(head), "\n") {
		if generatedHeaderRE.MatchString(strings.TrimLeft(line, "/*#-<!; \t")) {
			return true
		}
	}
	return strings.HasSuffix(lower, ".min.js") || strings.HasSuffix(lower, ".min.css") || isMinified(content)
}

// preprocessorDirectives are `#` lines that are code rather than comments in
// C-family sources.
var preprocessorDirectives = []string{
	"#include", "#pragma", "#define", "#undef", "#if", "#else", "#elif", "#endif", "#import", "#error", "#line", "#[", "#![",
}

// leadingCommentBlock returns the comment lines that open a file, up to the
// first line of code. It works on comment syntax shared across the supported
// languages rather than per language: the caller only needs to know where the
// banner ends, and a line that is wrongly taken for code merely ends it early.
func leadingCommentBlock(head string) string {
	var block strings.Builder
	inBlockComment := false
	for line := range strings.SplitSeq(head, "\n") {
		trimmed := strings.TrimSpace(line)
		switch {
		case inBlockComment:
			inBlockComment = !strings.Contains(trimmed, "*/")
		case trimmed == "" || trimmed == "<?php":
			continue
		case strings.HasPrefix(trimmed, "/*"):
			inBlockComment = !strings.Contains(trimmed, "*/")
		case strings.HasPrefix(trimmed, "<!--"):
			// Single-line HTML-style banner; nothing to track.
		case strings.HasPrefix(trimmed, "//") || strings.HasPrefix(trimmed, "--"):
		case strings.HasPrefix(trimmed, "#") && !hasAnyPrefix(trimmed, preprocessorDirectives):
		default:
			return block.String()
		}
		block.WriteString(trimmed)
		block.WriteByte('\n')
	}
	return block.String()
}
